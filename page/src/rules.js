// Подсказки о совместимости: код, который в песочнице не заработает, потому что требует
// информационной базы, форм или модулей конфигурации. Показываются над выводом и жёлтыми
// предупреждениями в редакторе.
//
// Регулярные выражения используют (?<![\p{L}\p{N}_]) вместо \b: в JS \b не работает с кириллицей.

// Заглушки БСП на языке 1С (browser/bsp/*.bsl, esbuild грузит их как текст). Список экспортных
// методов берём прямо из исходников, чтобы не вести его в двух местах.
import bspOgnKs from '../../browser/bsp/ОбщегоНазначенияКлиентСервер.bsl';
import bspOgn from '../../browser/bsp/ОбщегоНазначения.bsl';
import bspStrKs from '../../browser/bsp/СтроковыеФункцииКлиентСервер.bsl';

function exportedMethods(source) {
  const names = new Set();
  for (const m of source.matchAll(/^\s*(?:Процедура|Функция)\s+([\p{L}\p{N}_]+)\s*\([^)]*\)\s*Экспорт/gmu)) {
    names.add(m[1].toLowerCase());
  }
  return names;
}

/** Модуль БСП (в нижнем регистре) → множество методов-заглушек (в нижнем регистре) */
export const BSP_STUBS = new Map([
  ['общегоназначенияклиентсервер', exportedMethods(bspOgnKs)],
  ['общегоназначения', exportedMethods(bspOgn)],
  ['строковыефункцииклиентсервер', exportedMethods(bspStrKs)],
]);

const isStub = (module, method) => {
  const methods = BSP_STUBS.get(module.toLowerCase());
  return !!methods && methods.has(method.toLowerCase());
};

const B = '(?<![\\p{L}\\p{N}_])';

export const RULES = [
  { re: new RegExp(B + '(Справочники|Документы|РегистрыСведений|РегистрыНакопления|РегистрыБухгалтерии|Перечисления|Константы|ПланыСчетов|ПланыВидовХарактеристик|БизнесПроцессы|ЖурналыДокументов|Обработки|Отчеты)\\.', 'gu'),
    text: 'Объекты конфигурации (справочники, документы, регистры) существуют только внутри конкретной базы 1С.' },
  { re: /&(НаСервере|НаКлиенте|НаСервереБезКонтекста|НаКлиентеНаСервере)/gu, text: 'Директивы &НаКлиенте/&НаСервере здесь не разделяют код: всё выполняется в одном месте.' },
  {
    re: new RegExp(B + '(ОбщегоНазначения|ОбщегоНазначенияКлиент|ОбщегоНазначенияКлиентСервер|СтроковыеФункцииКлиентСервер|СтроковыеФункции|ОбщегоНазначенияСервер)\\s*\\.\\s*([\\p{L}\\p{N}_]+)', 'giu'),
    accept: (m) => !isStub(m[1], m[2]),
    text: 'Этой функции БСП (Библиотеки стандартных подсистем) в песочнице нет. Есть заглушки популярных функций ОбщегоНазначенияКлиентСервер, ОбщегоНазначения и СтроковыеФункцииКлиентСервер, которые не обращаются к базе; см. пример «Функции БСП».',
  },
  { re: new RegExp(B + '(?:(?:ЭтаФорма|ЭтотОбъект|ОткрытьФорму|ПолучитьФорму|ПоказатьПредупреждение|ПоказатьВопрос|ОповеститьОбИзменении)(?![\\p{L}\\p{N}_])|Элементы\\.)', 'gu'),
    text: 'Формы и интерфейс клиента в песочнице недоступны. Выводите результат через Сообщить().' },
];

/** Все срабатывания правил в коде: [{from, to, text}] */
export function findRuleMatches(code) {
  const result = [];
  for (const rule of RULES) {
    rule.re.lastIndex = 0;
    for (const m of code.matchAll(rule.re)) {
      if (rule.accept && !rule.accept(m)) continue;
      result.push({ from: m.index, to: m.index + m[0].trimEnd().length, text: rule.text });
    }
  }
  return result;
}

/** Тексты сработавших правил без повторов (для списка подсказок над выводом) */
export function findHints(code) {
  return [...new Set(findRuleMatches(code).map((m) => m.text))];
}
